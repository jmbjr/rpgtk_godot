import assert from 'node:assert/strict';
import {buildBackgroundGame} from '../docs/specs/fixtures/tk3-browser-fixtures.mjs';
import {readArtifacts,buildReferences} from '../artifacts.mjs';
import {buildPlayableScene} from '../playable-scene.mjs';
import {createTk3TaskScheduler,boardTaskBindings} from '../tk3-tasks.mjs';
import {initialTk3ScriptState} from '../tk3-script-slice.mjs';
for(const id of ['harbor','grove']) {
 const {artifacts}=await readArtifacts(await buildBackgroundGame(id),{});
 const scene=buildPlayableScene(artifacts,buildReferences(artifacts));
 const tasks=createTk3TaskScheduler(artifacts,scene.projectRoot);
 let state=initialTk3ScriptState();tasks.enter(scene,state);
 assert.equal(boardTaskBindings(scene,artifacts).length,2);
 for(let time=0;time<1000;time+=20)state=tasks.tick(state,time);
 assert.ok(state.variables.board_ticks>1 && state.variables.item_ticks>1);
 const before={...state.variables};state=tasks.tick(state,2000,true);assert.deepEqual(state.variables,before);
 const old=tasks.records.map(r=>r.id);
 const persistent=tasks.handle({name:'thread',args:['persistent_worker.prg',1],path:'caller',line:2},null,state.variables).value;
 tasks.enter(scene,state);
 assert.ok(tasks.records.some(t=>t.id===persistent));assert.ok(!tasks.records.some(t=>old.includes(t.id)));
 const item=tasks.records.find(t=>t.entitySlot===0);
 state={...state,erasedItems:{[scene.boardPath]:[0]}};
 state=tasks.tick(state,2020);assert.equal(tasks.records.find(t=>t.id===item.id).status,'paused-erased');
 assert.throws(()=>tasks.handle({name:'getthreadid',args:[]}),/outside/);
 tasks.handle({name:'threadsleep',args:[persistent,0]});tasks.tick(state,5000);assert.equal(tasks.records.find(t=>t.id===persistent).status,'sleeping');
 tasks.handle({name:'threadwake',args:[persistent]});
 tasks.handle({name:'killthread',args:[persistent]});assert.ok(!tasks.records.some(t=>t.id===persistent));
 const bad=tasks.handle({name:'thread',args:['bad_worker.prg',0],path:'caller',line:1}).value;
 assert.equal(tasks.records.find(t=>t.id===bad).status,'error');
 const count=state.variables.board_ticks;
 for(let time=6000;time<6200;time+=20)state=tasks.tick(state,time);
 assert.ok(state.variables.board_ticks>count,'A failed task does not stop healthy peers');
 const spinning=tasks.handle({name:'thread',args:['spin_worker.prg',0],path:'caller',line:1}).value;
 state=tasks.tick(state,6400);state=tasks.tick(state,6420);assert.ok(state.variables.spins>0);
 assert.equal(tasks.records.find(t=>t.id===spinning).status,'ready');
 while(tasks.records.length<32)tasks.handle({name:'thread',args:['persistent_worker.prg',0],path:'caller',line:1});
 assert.throws(()=>tasks.handle({name:'thread',args:['persistent_worker.prg',0],path:'caller',line:1}),/limit/);
 tasks.destroy();assert.deepEqual(tasks.records,[]);
}
console.log('Task scheduler passed: shared VM globals, cooperative progress/sleep/modal pause, board/persistent ownership, item erasure, wake/kill and disposal.');
