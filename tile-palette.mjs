// Return native-size, column-major RGB bytes for either TST encoding.
export function tilesetRgb({ bytes, width, height }, number) {
  const detail = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getInt16(4, true);
  const size = width * height;
  if (detail <= 2) return bytes.subarray(6 + (number - 1) * size * 3, 6 + number * size * 3);
  const rgb = new Uint8Array(size * 3);
  const start = 6 + (number - 1) * size;
  for (let i = 0; i < size; i++) {
    const index = bytes[start + i];
    const color = dosPalette[index];
    rgb.set(index === 255 ? [0, 1, 2] : [color & 255, (color >>> 8) & 255, color >>> 16], i * 3);
  }
  return rgb;
}
